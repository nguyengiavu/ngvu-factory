source "$(dirname "$0")/lib/assert.sh"
T=$(kf_tmp); kf_test_config "$T"; V="$KF_S/verdict.sh"
printf 'VERDICT: PASS\n\nbody\n' > "$T/r1"; assert_eq PASS "$(bash "$V" review "$T/r1")" "review pass"
printf 'VERDICT: CHANGES\r\nbody\r\n' > "$T/r2"; assert_eq CHANGES "$(bash "$V" review "$T/r2")" "CRLF tolerated"
printf '\xef\xbb\xbfVERDICT: PASS\n' > "$T/r3"; assert_eq PASS "$(bash "$V" review "$T/r3")" "BOM tolerated"
printf 'VERDICT: PASS   \n' > "$T/r4"; assert_eq PASS "$(bash "$V" review "$T/r4")" "trailing spaces tolerated"
printf 'STATUS: READY\n' > "$T/b1"; assert_eq READY "$(bash "$V" build "$T/b1")" "build ready"
printf 'STATUS: BLOCKED\n' > "$T/b2"; assert_eq BLOCKED "$(bash "$V" build "$T/b2")" "build blocked"
printf 'APPROVE\n' > "$T/d1"; assert_eq APPROVE "$(bash "$V" decision "$T/d1")" "approve"
printf 'ESCALATE\n' > "$T/d2"; assert_eq ESCALATE "$(bash "$V" decision "$T/d2")" "escalate"
printf '# Payer billing API\n' > "$T/s1"; assert_eq READY "$(bash "$V" spec "$T/s1")" "spec ready"
printf 'STATUS: BLOCKED\n' > "$T/s2"; assert_eq BLOCKED "$(bash "$V" spec "$T/s2")" "spec blocked"
printf 'Looks good to me\n' > "$T/x"; assert_exit 2 "malformed first line" bash "$V" review "$T/x"
assert_exit 2 "verdict of wrong kind" bash "$V" decision "$T/r1"
assert_exit 2 "missing file" bash "$V" review "$T/none"
kf_finish
